-- IM-06 (#212): TaskExecution-owned WorkOrder DRAFT creation facts.
-- Design authority: Module-Spec-003 §18.7 (approved #210 design), Module-Spec-003
-- §18.2/§18.3/§18.5, Module-Spec-001 §15.6/§15.7 and the decisions
-- `rls-transaction-context.md` §3.5 (`principalKind` increment, `V0004`).
--
-- One successful DRAFT creation commits one WorkOrder Aggregate Root and one
-- immutable WorkOrderDraftSnapshot in the same owning transaction. The Root
-- points at its snapshot through the composite pointer `(work_order_id,
-- current_draft_snapshot_id, current_draft_snapshot_hash)`; comparing the hash
-- as well as the snapshot id keeps a silently re-written payload from
-- satisfying the pointer, and the pointer can only move through a CAS
-- transition of the owning aggregate version (not implemented in this slice).
-- DRAFT creation writes **zero** `outbox_event` rows and publishes no Event: no
-- WorkOrder draft creation Event is registered in the Catalog (§18.10).
--
-- Public spelling (§18.2): a WorkOrder has exactly one accepted spelling and it
-- is derived from that WorkOrder's own creation fact -
-- `execution.create_work_order@1.0` (the historical Baseline entry) produced
-- `execution.work_order`, `@1.1` produced `zhiju.execution.work_order` - so the
-- creation-identity guard closes `workOrderRef.objectType` <-> Receipt
-- `command_version` <-> `draft_schema_version` <-> `work_order_object_type`
-- (four-way) and the canonical payload is projected onto the creation request
-- (`{draft}` plus `{expiresAt}` if and only if that member exists), so reusing
-- another command's Receipt with different content, relabelling a `@1.1`
-- payload as `1.0`, or adding/rewriting/JSON-null-ing `expiresAt` are all
-- refused in the database. The bound Task spelling is derived from that Task's
-- own creation definition snapshot `schema_version` (§18.3) and never from the
-- WorkOrder version, and `draft.taskRef`, the Snapshot's top-level `taskRef`,
-- the Root mirrors and the checked Task row (its `task_id`, Scope columns and
-- creation definition spelling) must be one fact.
--
-- Mirrors and content address: the snapshot's promoted columns (work order
-- spelling, Task spelling, Project Scope, nullable expiry, payload hash) are
-- re-derived in SQL from the stored canonical payload, so a direct write cannot
-- publish a snapshot whose mirrors or content address disagree with its own
-- bytes. `payload_hash` is
-- `sha256(convert_to(task_execution.canonical_jsonb_text(canonical_payload),
-- 'UTF8'))`, reusing the owner-only canonicalization-v1 helper V3001 created
-- (PostgreSQL 18 provides `sha256(bytea)`; pgcrypto stays disabled).
--
-- Ownership closure (§18.5 items 7-8): the trusted anchor is the platform
-- transaction context, not the Receipt's creator column. Both snapshot INSERT
-- and Root INSERT/UPDATE policies require the creator/requester columns to equal
-- `platform_security.context_principal_id()`, and the creation-identity guard
-- binds both payload `PrincipalRef`s - `draft.requestedBy` and `createdBy`, with
-- `principalId` and `principalKind` - to
-- `context_principal_id()`/`context_principal_kind()`. The kind helper returns
-- NULL for a legacy 10-parameter context, so a WorkOrder can never be created
-- from one.
--
-- RLS follows the V3000/V3001/V3002 conventions: FORCE, Project-scoped rows call
-- `context_allows_project(enterprise_id, project_id)`, so a WorkOrder can never
-- leak through an Enterprise-only or foreign-Project Context. No cross-Schema
-- FK/join is created and no other Schema's data is copied.

SET ROLE task_execution_owner;

-- ---------------------------------------------------------------------------
-- task_execution.work_order_draft_snapshot: the immutable WorkOrderDraft of one
-- WorkOrder. `snapshot_id` is generated by the application (UuidV7) and is
-- independent of the Root's CAS `aggregate_version`; `draft_schema_version`
-- records the CREATE major that produced the payload ('1.0' = `WorkOrderDraft`,
-- '1.1' = `InitialWorkOrderDraft`).
-- ---------------------------------------------------------------------------

CREATE TABLE task_execution.work_order_draft_snapshot (
    snapshot_id uuid PRIMARY KEY,
    work_order_id uuid NOT NULL,
    draft_schema_version text NOT NULL,
    work_order_object_type text NOT NULL,
    task_object_type text NOT NULL,
    enterprise_id uuid NOT NULL,
    project_id uuid NOT NULL,
    expires_at timestamptz,
    canonical_payload jsonb NOT NULL,
    payload_hash bytea NOT NULL,
    canonicalization_version text NOT NULL DEFAULT '1',
    request_payload_hash bytea NOT NULL,
    source_command_id uuid NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_principal_id uuid NOT NULL,
    CONSTRAINT work_order_draft_snapshot_schema_version_closed CHECK (
        draft_schema_version IN ('1.0', '1.1')),
    -- Each WorkOrder carries exactly one accepted public spelling (§18.2); the
    -- closed set is the two published creation majors' nouns, and the
    -- creation-identity guard below closes which of the two this row may carry.
    CONSTRAINT work_order_draft_snapshot_object_type_closed CHECK (
        work_order_object_type IN ('execution.work_order', 'zhiju.execution.work_order')),
    CONSTRAINT work_order_draft_snapshot_task_object_type_closed CHECK (
        task_object_type IN ('execution.task', 'zhiju.execution.task')),
    -- Both content addresses are SHA-256: a row with a short or absent digest
    -- could claim an identity the application cannot recompute.
    CONSTRAINT work_order_draft_snapshot_hash_len CHECK (
        octet_length(payload_hash) = 32
        AND octet_length(request_payload_hash) = 32),
    -- The payload is the §18.7 `WorkOrderDraftSnapshot` body, and the mirror
    -- guard below re-derives every promoted column from it. This constraint
    -- closes the cheap structural half of that contract so a payload whose
    -- members are not even of the right JSON kind is refused before any
    -- comparison runs. Every comparison is `IS NOT DISTINCT FROM`: a plain `=`
    -- against a missing JSON member yields NULL, and SQL would let a NULL CHECK
    -- pass.
    CONSTRAINT work_order_draft_snapshot_payload_shape CHECK (
        jsonb_typeof(canonical_payload) IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'workOrderRef') IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'taskRef') IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'scopeRef') IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'draft') IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'draft'->'taskRef')
            IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'draft'->'requestedBy')
            IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'createdBy') IS NOT DISTINCT FROM 'object'),
    -- Composite identity the Root pointer references: the same WorkOrder, the
    -- same snapshot and the exact canonical payload hash.
    CONSTRAINT work_order_draft_snapshot_pointer_unique UNIQUE (
        work_order_id, snapshot_id, payload_hash)
);

-- ---------------------------------------------------------------------------
-- task_execution.work_order: WorkOrder Aggregate Root. DRAFT creation writes
-- `status='DRAFT'` and `aggregate_version=1`; Scope, identity, spelling, draft
-- schema version and the expiry are immutable after creation.
-- `(enterprise_id, project_id)` is the Project Scope the Root can never leave.
-- ---------------------------------------------------------------------------

CREATE TABLE task_execution.work_order (
    work_order_id uuid PRIMARY KEY,
    enterprise_id uuid NOT NULL,
    project_id uuid NOT NULL,
    work_order_object_type text NOT NULL,
    task_id uuid NOT NULL,
    task_object_type text NOT NULL,
    status text NOT NULL DEFAULT 'DRAFT',
    aggregate_version bigint NOT NULL DEFAULT 1,
    current_draft_snapshot_id uuid NOT NULL,
    current_draft_snapshot_hash bytea NOT NULL,
    draft_schema_version text NOT NULL,
    expires_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_principal_id uuid NOT NULL,
    requested_by_principal_id uuid NOT NULL,
    CONSTRAINT work_order_status_closed CHECK (
        status IN ('DRAFT', 'READY', 'QUEUED', 'RUNNING', 'WAITING_INPUT',
                   'COMPLETION_PENDING', 'RETRY_PENDING', 'COMPLETED', 'FAILED',
                   'CANCELLED', 'EXPIRED')),
    CONSTRAINT work_order_version_positive CHECK (aggregate_version >= 1),
    CONSTRAINT work_order_object_type_closed CHECK (
        work_order_object_type IN ('execution.work_order', 'zhiju.execution.work_order')),
    CONSTRAINT work_order_task_object_type_closed CHECK (
        task_object_type IN ('execution.task', 'zhiju.execution.task')),
    CONSTRAINT work_order_draft_schema_version_closed CHECK (
        draft_schema_version IN ('1.0', '1.1')),
    CONSTRAINT work_order_draft_hash_len CHECK (
        octet_length(current_draft_snapshot_hash) = 32),
    CONSTRAINT work_order_scope_unique UNIQUE (enterprise_id, project_id, work_order_id),
    CONSTRAINT work_order_draft_pointer_fk FOREIGN KEY (
        work_order_id, current_draft_snapshot_id, current_draft_snapshot_hash)
        REFERENCES task_execution.work_order_draft_snapshot
            (work_order_id, snapshot_id, payload_hash)
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED
);

-- ---------------------------------------------------------------------------
-- Creation-request projection hash.
-- ---------------------------------------------------------------------------

-- §18.7 closes the snapshot against the in-flight CREATE request through a
-- projection of the canonical payload that the database can rebuild:
-- `request(canonical_payload) = {draft: canonical_payload->'draft'}`, plus
-- `{expiresAt: canonical_payload->'expiresAt'}` if and only if that member
-- exists. The registered `create_work_order` payload is closed to exactly
-- `draft` and the optional `expiresAt`, so there is no unknown-member branch,
-- and the Snapshot header (`snapshotId`/`workOrderRef`/`taskRef`/`scopeRef`/
-- `capturedAt`/`createdBy`) must NOT enter the projection: only `draft` is
-- proven to come from the command, the header is derived write.
--
-- Member *presence* participates through the `?` operator, so removing the
-- member, rewriting its value or replacing it with JSON null all change the
-- projection hash (an `instant` member can never be JSON null in the registered
-- Envelope).
--
-- SECURITY DEFINER: the canonicalizer is owner-only (V3001 revoked it from
-- `task_execution_app`), and this helper is called from the SECURITY INVOKER
-- creation-identity guard, where a nested call is permission-checked against the
-- writing role. Running the hash as its owner keeps `canonical_jsonb_text`
-- unreachable for the application role while the receipt's request hash is still
-- recomputed in the database. The function reads no table and only hashes its
-- own argument, so its EXECUTE grant exposes no data and no RLS boundary; it
-- must be executable by the app role because the invoker guard calls it.
CREATE FUNCTION task_execution.work_order_draft_request_hash(p_payload jsonb)
RETURNS bytea
LANGUAGE sql
IMMUTABLE
STRICT
SECURITY DEFINER
SET search_path = pg_catalog
AS $fn$
    SELECT sha256(convert_to(
        task_execution.canonical_jsonb_text(
            CASE
                WHEN p_payload ? 'expiresAt' THEN
                    jsonb_build_object(
                        'draft', p_payload->'draft',
                        'expiresAt', p_payload->'expiresAt')
                ELSE
                    jsonb_build_object('draft', p_payload->'draft')
            END),
        'UTF8'));
$fn$;

REVOKE ALL ON FUNCTION task_execution.work_order_draft_request_hash(jsonb) FROM PUBLIC;
-- The V0002 default privileges would grant this anyway (the owner creates the
-- function); granting it explicitly keeps the invoker guard's requirement
-- independent of that default.
GRANT EXECUTE ON FUNCTION task_execution.work_order_draft_request_hash(jsonb)
    TO task_execution_app;

-- ---------------------------------------------------------------------------
-- Payload mirror guard.
-- ---------------------------------------------------------------------------

-- The promoted columns must agree with the canonical payload: a snapshot cannot
-- be published under a spelling, a Project Scope or an expiry that its own
-- payload does not carry, and `payload_hash` must be recomputable from the
-- stored bytes by the shared-kernel canonicalization v1 rules. The `expires_at`
-- mirror is null-safe in both directions: a missing member compares as NULL, so
-- "absent" and "NULL column" agree while a JSON null can never masquerade as
-- `expiresAt` with a value (its presence is still caught by the projection hash
-- in the creation-identity guard).
--
-- SECURITY DEFINER: the guard calls the owner-only canonicalizer, and a
-- permission check on that nested call is evaluated against the role that
-- performed the write. Running the guard as its owner keeps the canonicalizer
-- unreachable for the application role while every insert still re-derives the
-- content address in the database. The function only reads its own NEW row and
-- cannot be invoked directly (trigger functions are trigger-only).
--
-- The `expiresAt` comparison casts a member of `canonical_payload`, so a
-- malformed payload would otherwise surface as a cast error instead of this
-- guard's stable identity. A preceding CHECK cannot close that: a CHECK cannot
-- express "this text is a parseable timestamptz" without pinning one spelling,
-- and the canonical payload format deliberately does not fix the instant
-- spelling (an offset form is the same instant), so a regex would reject
-- payloads the application may legally produce. The comparison is therefore
-- guarded: a payload-data failure is treated as a mirror mismatch and reported
-- as the single guard error, because the write is rejected either way and the
-- application should only ever see one code for "the stored payload cannot
-- define these columns". Failures that are not properties of the payload (for
-- example a missing guard helper) keep their own code, so a broken deployment
-- stays distinguishable from a bad write.
CREATE FUNCTION task_execution.guard_work_order_draft_snapshot_mirror() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $guard$
DECLARE
    mirror_mismatch boolean;
BEGIN
    -- The comparison runs in a nested block so a payload that cannot be cast
    -- fails the guard rather than escaping as a cast error; the guard's own
    -- rejection is raised afterwards, outside that block, so the failure this
    -- function reports is always this one statement.
    BEGIN
        mirror_mismatch := (
            NEW.work_order_object_type
                IS DISTINCT FROM NEW.canonical_payload->'workOrderRef'->>'objectType'
            OR NEW.task_object_type
                IS DISTINCT FROM NEW.canonical_payload->'taskRef'->>'objectType'
            OR NEW.enterprise_id::text
                IS DISTINCT FROM NEW.canonical_payload->'scopeRef'->>'enterpriseId'
            OR NEW.project_id::text
                IS DISTINCT FROM NEW.canonical_payload->'scopeRef'->>'projectId'
            OR NEW.expires_at
                IS DISTINCT FROM (NEW.canonical_payload->>'expiresAt')::timestamptz
            OR NEW.payload_hash
                IS DISTINCT FROM sha256(convert_to(
                       task_execution.canonical_jsonb_text(NEW.canonical_payload), 'UTF8')));
    EXCEPTION
        WHEN invalid_text_representation
          OR invalid_datetime_format
          OR datetime_field_overflow
          OR numeric_value_out_of_range
          OR invalid_parameter_value THEN
            -- Includes 22023 raised by the canonicalizer itself: that is the
            -- same class of defect (bytes that cannot define these columns),
            -- and it must not escape under a different message.
            mirror_mismatch := true;
    END;
    IF mirror_mismatch THEN
        RAISE EXCEPTION 'work order draft snapshot promoted mirror mismatch'
            USING ERRCODE = '22023';
    END IF;
    RETURN NEW;
END
$guard$;

REVOKE ALL ON FUNCTION task_execution.guard_work_order_draft_snapshot_mirror() FROM PUBLIC;

CREATE TRIGGER work_order_draft_snapshot_mirror_guard
    BEFORE INSERT OR UPDATE ON task_execution.work_order_draft_snapshot
    FOR EACH ROW EXECUTE FUNCTION task_execution.guard_work_order_draft_snapshot_mirror();

-- ---------------------------------------------------------------------------
-- Creation identity guard.
-- ---------------------------------------------------------------------------

-- The snapshot must be written by the in-flight transaction of the very command
-- it claims. `source_command_id` must name a `command_receipt` row for
-- `execution.create_work_order` that is still `PENDING`, whose
-- `command_version` equals the promoted `draft_schema_version`, whose
-- `target_type` equals the promoted `work_order_object_type` and whose
-- `target_id` plus Project Scope are this WorkOrder. The Receipt already
-- commits the canonical hash of the request the command was claimed for, so
-- requiring `request_payload_hash` to equal the projection hash rebuilt from
-- the stored payload proves the stored draft *is* the payload of that command:
-- without it a real Receipt could be reused with different content that carries
-- its own self-consistent `payload_hash`, and a snapshot could be retro-fitted
-- after its command was finalized.
--
-- Four-way spelling agreement: the payload's `workOrderRef.objectType`, the
-- Receipt's `command_version`, the promoted `draft_schema_version` and the
-- promoted `workOrder_object_type` are one fact, so a `@1.1` payload relabelled
-- `1.0` (or a legacy row claiming the canonical noun) has no Receipt that agrees
-- with all four.
--
-- Task identity closure (§18.3 item 6): `draft.taskRef`, the Snapshot's
-- top-level `taskRef`, the Root mirrors and the checked `task_execution.task`
-- row are one fact - `kind='OBJECT'`, equal `objectType`, equal `objectId` and
-- equal Project Scope members - and the Task spelling is derived from that
-- Task's own creation definition snapshot `schema_version`, never from the
-- WorkOrder version. Only `draft.taskRef` is proven by the creation request
-- projection to come from this command; the top-level reference and the Root
-- mirrors are derived write, so they must be compared here instead of being
-- trusted from the writer.
--
-- Ownership closure (§18.5 items 7-8): the trusted anchor is the transaction
-- context. Both payload `PrincipalRef`s (`draft.requestedBy` and `createdBy`)
-- must carry `principalId` and `principalKind` equal to
-- `context_principal_id()`/`context_principal_kind()`, the Root's two principal
-- ids and the Receipt's `created_by_principal_id` must equal
-- `context_principal_id()`, and a NULL kind (legacy context, or a missing
-- helper) rejects. The Receipt's creator column is deliberately not an anchor:
-- it is caller-writable, so it must agree with the context rather than replace
-- it.
--
-- SECURITY INVOKER on purpose: the Root, the Receipt, the Task row and its
-- definition snapshot are read under the same RLS policies and trusted Scope
-- the writer itself is subject to, so a hidden row is indistinguishable from a
-- missing one and the guard fails closed instead of trusting a row the
-- transaction may not see.
CREATE FUNCTION task_execution.guard_work_order_draft_snapshot_creation_identity()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $guard$
DECLARE
    root_found boolean;
    root_enterprise_id uuid;
    root_project_id uuid;
    root_work_order_object_type text;
    root_task_id uuid;
    root_task_object_type text;
    root_draft_schema_version text;
    root_expires_at timestamptz;
    root_created_by_principal_id uuid;
    root_requested_by_principal_id uuid;
    root_current_draft_snapshot_id uuid;
    root_current_draft_snapshot_hash bytea;
    receipt_found boolean;
    receipt_command_version text;
    receipt_target_type text;
    receipt_target_id uuid;
    receipt_enterprise_id uuid;
    receipt_project_id uuid;
    receipt_request_payload_hash bytea;
    receipt_outcome text;
    receipt_created_by_principal_id uuid;
    task_found boolean;
    task_enterprise_id uuid;
    task_project_id uuid;
    task_definition_schema_version text;
    payload_expires_at timestamptz;
    payload_expires_at_readable boolean := true;
    context_principal_id uuid;
    context_principal_kind text;
BEGIN
    -- The Root is inserted first and this snapshot second (the pointer FK is
    -- deferrable), so the creation fact this snapshot belongs to is readable
    -- here and cannot be re-pointed after the fact.
    SELECT w.enterprise_id, w.project_id, w.work_order_object_type, w.task_id,
           w.task_object_type, w.draft_schema_version, w.expires_at,
           w.created_by_principal_id, w.requested_by_principal_id,
           w.current_draft_snapshot_id, w.current_draft_snapshot_hash
      INTO root_enterprise_id, root_project_id, root_work_order_object_type,
           root_task_id, root_task_object_type, root_draft_schema_version,
           root_expires_at, root_created_by_principal_id,
           root_requested_by_principal_id, root_current_draft_snapshot_id,
           root_current_draft_snapshot_hash
      FROM task_execution.work_order w
     WHERE w.work_order_id = NEW.work_order_id;
    root_found := FOUND;

    SELECT r.command_version, r.target_type, r.target_id, r.enterprise_id,
           r.project_id, r.request_payload_hash, r.outcome,
           r.created_by_principal_id
      INTO receipt_command_version, receipt_target_type, receipt_target_id,
           receipt_enterprise_id, receipt_project_id,
           receipt_request_payload_hash, receipt_outcome,
           receipt_created_by_principal_id
      FROM task_execution.command_receipt r
     WHERE r.command_id = NEW.source_command_id
       AND r.command_type = 'execution.create_work_order';
    receipt_found := FOUND;

    -- The bound Task: its row, its Project Scope and the spelling derived from
    -- its own creation definition snapshot (`'1.0'` -> legacy, `'2.0'` ->
    -- canonical, §18.3 / R-206-1). A missing row or a missing definition
    -- snapshot fails the guard instead of being guessed from the payload. The
    -- creation definition snapshot is resolved through the Task's own current
    -- pointer: `execution.create_task` is the only producer of definition
    -- snapshots in this module, so the Task's committed definition *is* its
    -- creation definition, and V3001's guard already proved that snapshot's
    -- `schema_version` equals the `command_version` of the Receipt that created
    -- it.
    SELECT t.enterprise_id, t.project_id, s.schema_version
      INTO task_enterprise_id, task_project_id, task_definition_schema_version
      FROM task_execution.task t
      JOIN task_execution.task_definition_snapshot s
        ON s.task_id = t.task_id
       AND s.snapshot_id = t.current_definition_snapshot_id
       AND s.payload_hash = t.current_definition_hash
     WHERE t.task_id = root_task_id;
    task_found := FOUND;

    -- The payload's `expiresAt` member is cast in a nested block for the same
    -- reason as in the mirror guard: a payload that cannot define the column
    -- must fail this guard rather than escape as a cast error.
    BEGIN
        payload_expires_at := (NEW.canonical_payload->>'expiresAt')::timestamptz;
    EXCEPTION
        WHEN invalid_text_representation
          OR invalid_datetime_format
          OR datetime_field_overflow
          OR numeric_value_out_of_range
          OR invalid_parameter_value THEN
            payload_expires_at_readable := false;
    END;

    context_principal_id := platform_security.context_principal_id();
    context_principal_kind := platform_security.context_principal_kind();

    -- Root identity and Scope, the Root's own pointer back to this snapshot,
    -- the expiry member's presence and value, and the spelling this Root may
    -- carry for its `draft_schema_version`.
    IF NOT root_found
       OR root_enterprise_id IS DISTINCT FROM NEW.enterprise_id
       OR root_project_id IS DISTINCT FROM NEW.project_id
       OR root_work_order_object_type IS DISTINCT FROM NEW.work_order_object_type
       OR root_task_id::text
              IS DISTINCT FROM NEW.canonical_payload->'draft'->'taskRef'->>'objectId'
       OR root_task_object_type IS DISTINCT FROM NEW.task_object_type
       OR root_draft_schema_version IS DISTINCT FROM NEW.draft_schema_version
       OR root_current_draft_snapshot_id IS DISTINCT FROM NEW.snapshot_id
       OR root_current_draft_snapshot_hash IS DISTINCT FROM NEW.payload_hash
       OR NEW.work_order_object_type IS DISTINCT FROM (
              CASE NEW.draft_schema_version
                  WHEN '1.0' THEN 'execution.work_order'
                  ELSE 'zhiju.execution.work_order'
              END)
       OR NOT payload_expires_at_readable
       OR root_expires_at IS DISTINCT FROM payload_expires_at THEN
        RAISE EXCEPTION 'work order draft snapshot creation identity mismatch'
            USING ERRCODE = '22023';
    END IF;

    -- Source Receipt identity, its Project Scope, the request projection and the
    -- four-way spelling agreement.
    IF NOT receipt_found
       OR receipt_outcome IS DISTINCT FROM 'PENDING'
       OR receipt_command_version IS DISTINCT FROM NEW.draft_schema_version
       OR receipt_target_type IS DISTINCT FROM NEW.work_order_object_type
       OR receipt_target_id IS DISTINCT FROM NEW.work_order_id
       OR receipt_enterprise_id IS DISTINCT FROM NEW.enterprise_id
       OR receipt_project_id IS DISTINCT FROM NEW.project_id
       OR receipt_request_payload_hash IS DISTINCT FROM
              task_execution.work_order_draft_request_hash(NEW.canonical_payload)
       -- The promoted column is not evidence by itself; it is only meaningful
       -- once it equals the Receipt hash that the projection was just proven
       -- against.
       OR NEW.request_payload_hash IS DISTINCT FROM receipt_request_payload_hash
       OR NEW.canonical_payload->'workOrderRef'->>'kind' IS DISTINCT FROM 'OBJECT'
       OR NEW.canonical_payload->'workOrderRef'->>'objectType'
              IS DISTINCT FROM NEW.work_order_object_type
       OR NEW.canonical_payload->'workOrderRef'->>'objectId'
              IS DISTINCT FROM NEW.work_order_id::text
       OR NEW.canonical_payload->'workOrderRef'->'scope'->>'enterpriseId'
              IS DISTINCT FROM NEW.enterprise_id::text
       OR NEW.canonical_payload->'workOrderRef'->'scope'->>'projectId'
              IS DISTINCT FROM NEW.project_id::text THEN
        RAISE EXCEPTION 'work order draft snapshot creation identity mismatch'
            USING ERRCODE = '22023';
    END IF;

    -- Task identity closure: the declared `draft.taskRef`, the Snapshot's
    -- top-level `taskRef`, the Root mirrors and the checked Task row are one
    -- fact, and the Task spelling comes from that Task's creation definition
    -- snapshot.
    IF NOT task_found
       OR NEW.canonical_payload->'draft'->'taskRef'->>'kind' IS DISTINCT FROM 'OBJECT'
       OR NEW.canonical_payload->'taskRef'->>'kind' IS DISTINCT FROM 'OBJECT'
       OR NEW.canonical_payload->'draft'->'taskRef'->>'objectType'
              IS DISTINCT FROM NEW.task_object_type
       OR NEW.canonical_payload->'taskRef'->>'objectType'
              IS DISTINCT FROM NEW.task_object_type
       OR NEW.task_object_type IS DISTINCT FROM (
              CASE task_definition_schema_version
                  WHEN '2.0' THEN 'zhiju.execution.task'
                  ELSE 'execution.task'
              END)
       OR NEW.canonical_payload->'draft'->'taskRef'->>'objectId'
              IS DISTINCT FROM root_task_id::text
       OR NEW.canonical_payload->'taskRef'->>'objectId'
              IS DISTINCT FROM root_task_id::text
       OR NEW.canonical_payload->'draft'->'taskRef'->'scope'->>'enterpriseId'
              IS DISTINCT FROM NEW.enterprise_id::text
       OR NEW.canonical_payload->'draft'->'taskRef'->'scope'->>'projectId'
              IS DISTINCT FROM NEW.project_id::text
       OR NEW.canonical_payload->'taskRef'->'scope'->>'enterpriseId'
              IS DISTINCT FROM NEW.enterprise_id::text
       OR NEW.canonical_payload->'taskRef'->'scope'->>'projectId'
              IS DISTINCT FROM NEW.project_id::text
       OR task_enterprise_id IS DISTINCT FROM NEW.enterprise_id
       OR task_project_id IS DISTINCT FROM NEW.project_id THEN
        RAISE EXCEPTION 'work order draft snapshot creation identity mismatch'
            USING ERRCODE = '22023';
    END IF;

    -- Ownership closure: the context principal id *and* kind are the only
    -- trusted anchor, and a NULL kind (legacy context) can never create a
    -- WorkOrder.
    IF context_principal_kind IS NULL
       OR NEW.canonical_payload->'draft'->'requestedBy'->>'principalId'
              IS DISTINCT FROM context_principal_id::text
       OR NEW.canonical_payload->'draft'->'requestedBy'->>'principalKind'
              IS DISTINCT FROM context_principal_kind
       OR NEW.canonical_payload->'createdBy'->>'principalId'
              IS DISTINCT FROM context_principal_id::text
       OR NEW.canonical_payload->'createdBy'->>'principalKind'
              IS DISTINCT FROM context_principal_kind
       OR root_created_by_principal_id IS DISTINCT FROM context_principal_id
       OR root_requested_by_principal_id IS DISTINCT FROM context_principal_id
       OR receipt_created_by_principal_id IS DISTINCT FROM context_principal_id THEN
        RAISE EXCEPTION 'work order draft snapshot creation identity mismatch'
            USING ERRCODE = '22023';
    END IF;

    RETURN NEW;
END
$guard$;

