LANGUAGE plpgsql
SET search_path = pg_catalog
AS $guard$
BEGIN
    RAISE EXCEPTION 'work_order_draft_snapshot history is immutable' USING ERRCODE = '23514';
END
$guard$;

REVOKE ALL ON FUNCTION task_execution.guard_work_order_draft_snapshot_immutable() FROM PUBLIC;

CREATE TRIGGER work_order_draft_snapshot_immutable_guard
    BEFORE UPDATE OR DELETE ON task_execution.work_order_draft_snapshot
    FOR EACH ROW EXECUTE FUNCTION task_execution.guard_work_order_draft_snapshot_immutable();

-- The Root keeps an update path for later lifecycle/CAS slices, but identity,
-- Project Scope, both spellings, the draft schema version, the expiry and the
-- creation attribution are creation facts: a later command may move the status,
-- the aggregate version and the draft pointer, never the Scope, and the Root is
-- never deletable. Re-pointing `current_draft_*` is a change of the committed
-- draft, so it must be a deliberate CAS transition: the aggregate version has to
-- advance in the same UPDATE, and the new pointer must name a `(snapshot_id,
-- payload_hash)` pair that exists for this very WorkOrder. Without that rule the
-- draft identity could be swapped silently, and a snapshot row that is merely
-- present would be enough to replace the current draft.
CREATE FUNCTION task_execution.guard_work_order_root_update() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $guard$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'work_order root is not deletable' USING ERRCODE = '23514';
    END IF;
    IF NEW.work_order_id IS DISTINCT FROM OLD.work_order_id
       OR NEW.enterprise_id IS DISTINCT FROM OLD.enterprise_id
       OR NEW.project_id IS DISTINCT FROM OLD.project_id
       OR NEW.work_order_object_type IS DISTINCT FROM OLD.work_order_object_type
       OR NEW.task_id IS DISTINCT FROM OLD.task_id
       OR NEW.task_object_type IS DISTINCT FROM OLD.task_object_type
       OR NEW.draft_schema_version IS DISTINCT FROM OLD.draft_schema_version
       OR NEW.expires_at IS DISTINCT FROM OLD.expires_at
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.created_by_principal_id IS DISTINCT FROM OLD.created_by_principal_id
       OR NEW.requested_by_principal_id IS DISTINCT FROM OLD.requested_by_principal_id THEN
        RAISE EXCEPTION 'work order identity and scope are immutable' USING ERRCODE = '23514';
    END IF;
    IF (NEW.current_draft_snapshot_id, NEW.current_draft_snapshot_hash)
       IS DISTINCT FROM (OLD.current_draft_snapshot_id, OLD.current_draft_snapshot_hash) THEN
        IF NEW.aggregate_version <= OLD.aggregate_version THEN
            RAISE EXCEPTION 'work order draft pointer change must advance the aggregate version'
                USING ERRCODE = '23514';
        END IF;
        IF NOT EXISTS (
            SELECT 1
              FROM task_execution.work_order_draft_snapshot s
             WHERE s.work_order_id = NEW.work_order_id
               AND s.snapshot_id = NEW.current_draft_snapshot_id
               AND s.payload_hash = NEW.current_draft_snapshot_hash) THEN
            RAISE EXCEPTION 'work order draft pointer must reference a snapshot of this work order'
                USING ERRCODE = '23514';
        END IF;
    END IF;
    RETURN NEW;
END
$guard$;

REVOKE ALL ON FUNCTION task_execution.guard_work_order_root_update() FROM PUBLIC;

CREATE TRIGGER work_order_root_update_guard
    BEFORE UPDATE OR DELETE ON task_execution.work_order
    FOR EACH ROW EXECUTE FUNCTION task_execution.guard_work_order_root_update();

