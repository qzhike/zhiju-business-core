-- IM-06 (#204): TaskExecution-owned Task DRAFT creation facts.
-- Design authority: Module-Spec-003 §16 (approved #202 design),
-- Module-Spec-002 §13.1 and the PostgreSQL logical model §33 (#202 increment).
--
-- One successful DRAFT creation commits one Task Aggregate Root and one
-- immutable TaskDefinitionSnapshot in the same owning transaction. The Root
-- points at its snapshot through a composite pointer `(task_id,
-- current_definition_snapshot_id, current_definition_hash)`; comparing the hash
-- as well as the snapshot id keeps a silently re-written definition from
-- satisfying the pointer. DRAFT creation writes no `outbox_event` row: no Task
-- creation Event is registered in the Catalog.
--
-- Mirrors and content address: the snapshot's promoted columns (Project scope,
-- DeliveryItem mirrors, schema version, payload hash) are re-derived in SQL
-- from the stored canonical payload, so a direct write cannot publish a
-- snapshot whose mirrors, scope or content address disagree with its own bytes.
-- `payload_hash` is `sha256(canonical_jsonb_text(canonical_payload))`, matching
-- the shared-kernel canonicalization v1 rules the application uses
-- (PostgreSQL 18 provides `sha256(bytea)`; pgcrypto stays disabled).
--
-- RLS follows the V3000 conventions: FORCE, Project-scoped rows call
-- `context_allows_project(enterprise_id, project_id)` so a Task can never leak
-- through an Enterprise-only Context.

SET ROLE task_execution_owner;

-- ---------------------------------------------------------------------------
-- task_definition_snapshot: the immutable TaskDefinition of one Task.
-- `snapshot_id` is generated by the application and is independent of the
-- Root's CAS `aggregate_version`; `schema_version` records the CREATE version
-- that produced the payload ('1.0' = TaskDefinition, '2.0' = TaskDefinitionV2).
-- ---------------------------------------------------------------------------

CREATE TABLE task_execution.task_definition_snapshot (
    snapshot_id uuid PRIMARY KEY,
    task_id uuid NOT NULL,
    schema_version text NOT NULL,
    enterprise_id uuid NOT NULL,
    project_id uuid NOT NULL,
    delivery_item_id uuid,
    delivery_item_version_id uuid,
    canonical_payload jsonb NOT NULL,
    payload_hash bytea NOT NULL,
    canonicalization_version text NOT NULL DEFAULT '1',
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_principal_id uuid NOT NULL,
    source_command_id uuid NOT NULL,
    CONSTRAINT task_definition_snapshot_schema_version_closed CHECK (
        schema_version IN ('1.0', '2.0')),
    CONSTRAINT task_definition_snapshot_hash_len CHECK (octet_length(payload_hash) = 32),
    CONSTRAINT task_definition_snapshot_delivery_item_pair CHECK (
        (delivery_item_id IS NULL) = (delivery_item_version_id IS NULL)),
    -- Every comparison is `IS NOT DISTINCT FROM`: a plain `=` against a
    -- missing JSON member yields NULL, and SQL would let a NULL CHECK pass.
    CONSTRAINT task_definition_snapshot_payload_shape CHECK (
        jsonb_typeof(canonical_payload) IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'projectRef') IS NOT DISTINCT FROM 'object'
        AND jsonb_typeof(canonical_payload->'definition') IS NOT DISTINCT FROM 'object'),
    -- The @2.0 payload is a closed shape (§11.6): a snapshot that claims the
    -- v2 schema version must carry its `expectedOutputSpec`/`completionCriteria`
    -- shapes. The historical v1 members stay open JSON, so only this direction
    -- is provable from the payload; the other direction is closed by the
    -- creation-identity guard below. Comparisons use `IS NOT DISTINCT FROM`
    -- because a missing member compares as NULL, which a plain CHECK would
    -- treat as satisfied.
    CONSTRAINT task_definition_snapshot_v2_shape CHECK (
        schema_version <> '2.0'
        OR (jsonb_typeof(canonical_payload->'definition'->'expectedOutputSpec')
                IS NOT DISTINCT FROM 'object'
            AND canonical_payload->'definition'->'expectedOutputSpec'->>'schemaVersion'
                IS NOT DISTINCT FROM '1.0'
            AND jsonb_typeof(canonical_payload->'definition'->'expectedOutputSpec'->'outputs')
                IS NOT DISTINCT FROM 'array'
            AND jsonb_typeof(canonical_payload->'definition'->'completionCriteria')
                IS NOT DISTINCT FROM 'object'
            AND canonical_payload->'definition'->'completionCriteria'->>'schemaVersion'
                IS NOT DISTINCT FROM '1.0'
            AND jsonb_typeof(canonical_payload->'definition'->'completionCriteria'->'criteria')
                IS NOT DISTINCT FROM 'array')),
    -- Composite identity the Root pointer references: the same Task, the same
    -- snapshot and the exact canonical payload hash.
    CONSTRAINT task_definition_snapshot_pointer_unique UNIQUE (
        task_id, snapshot_id, payload_hash)
);

CREATE INDEX task_definition_snapshot_task_idx
    ON task_execution.task_definition_snapshot (task_id, created_at DESC);
CREATE INDEX task_definition_snapshot_scope_idx
    ON task_execution.task_definition_snapshot (enterprise_id, project_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- task: Task Aggregate Root. DRAFT creation writes `status='DRAFT'` and
-- `aggregate_version=1`; Scope columns and the definition identity are
-- immutable after creation. `(enterprise_id, project_id)` is the Project Scope
-- the Root can never leave.
-- ---------------------------------------------------------------------------

CREATE TABLE task_execution.task (
    task_id uuid PRIMARY KEY,
    enterprise_id uuid NOT NULL,
    project_id uuid NOT NULL,
    status text NOT NULL DEFAULT 'DRAFT',
    aggregate_version bigint NOT NULL DEFAULT 1,
    current_definition_snapshot_id uuid NOT NULL,
    current_definition_hash bytea NOT NULL,
    delivery_item_id uuid,
    delivery_item_version_id uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_principal_id uuid NOT NULL,
    CONSTRAINT task_status_closed CHECK (
        status IN ('DRAFT', 'BACKLOG', 'READY', 'IN_PROGRESS', 'WAITING_INPUT', 'BLOCKED',
                   'IN_REVIEW', 'CHANGES_REQUIRED', 'COMPLETION_PENDING', 'COMPLETED',
                   'CANCELLED')),
    CONSTRAINT task_version_positive CHECK (aggregate_version >= 1),
    CONSTRAINT task_definition_hash_len CHECK (octet_length(current_definition_hash) = 32),
    CONSTRAINT task_delivery_item_pair CHECK (
        (delivery_item_id IS NULL) = (delivery_item_version_id IS NULL)),
    CONSTRAINT task_scope_unique UNIQUE (enterprise_id, project_id, task_id),
    CONSTRAINT task_definition_pointer_fk FOREIGN KEY (
        task_id, current_definition_snapshot_id, current_definition_hash)
        REFERENCES task_execution.task_definition_snapshot
            (task_id, snapshot_id, payload_hash)
        ON DELETE RESTRICT DEFERRABLE INITIALLY DEFERRED
);

CREATE INDEX task_scope_status_idx
    ON task_execution.task (enterprise_id, project_id, status, created_at DESC);
CREATE INDEX task_delivery_item_idx
    ON task_execution.task (enterprise_id, project_id, delivery_item_id)
    WHERE delivery_item_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Canonical payload text and the snapshot mirror guard.
-- ---------------------------------------------------------------------------

-- PostgreSQL 18 provides sha256(bytea); this local canonicalizer mirrors the
-- shared-kernel canonicalization v1 rules (NFC-normalized strings, UTF-8 byte
-- order of object keys, safe integers only, and the refusal of property names
-- that collide after NFC normalization) without enabling pgcrypto, so the
-- stored definition content address can be recomputed from the stored payload
-- inside the database. JSONB keeps two original keys that normalize to one
-- string, and the application canonicalizer rejects that payload, so the
-- database recomputation must reject it identically instead of publishing a
-- content address no application can reproduce. It is a guard helper only and
-- is not granted to the application role.
CREATE FUNCTION task_execution.canonical_jsonb_text(p_value jsonb)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
STRICT
SET search_path = pg_catalog
AS $fn$
DECLARE
    item record;
    kind text;
    result text;
    separator text := '';
    number_value numeric;
    normalized_key text;
    previous_key text;
BEGIN
    kind := jsonb_typeof(p_value);
    IF kind = 'object' THEN
        result := '{';
        FOR item IN
            SELECT key, value
              FROM jsonb_each(p_value)
             ORDER BY encode(convert_to(normalize(key, NFC), 'UTF8'), 'hex')
        LOOP
            normalized_key := normalize(item.key, NFC);
            -- The scan is ordered by the normalized bytes, so a collision is
            -- always adjacent to its twin.
            IF normalized_key = previous_key THEN
                RAISE EXCEPTION 'canonical JSON property names collide after NFC normalization'
                    USING ERRCODE = '22023';
            END IF;
            previous_key := normalized_key;
            result := result
                || separator
                || to_jsonb(normalized_key)::text
                || ':'
                || task_execution.canonical_jsonb_text(item.value);
            separator := ',';
        END LOOP;
        RETURN result || '}';
    ELSIF kind = 'array' THEN
        result := '[';
        FOR item IN
            SELECT value
              FROM jsonb_array_elements(p_value) WITH ORDINALITY AS elements(value, ordinal)
             ORDER BY ordinal
        LOOP
            result := result
                || separator
                || task_execution.canonical_jsonb_text(item.value);
            separator := ',';
        END LOOP;
        RETURN result || ']';
    ELSIF kind = 'string' THEN
        RETURN to_jsonb(normalize(p_value #>> '{}', NFC))::text;
    ELSIF kind = 'number' THEN
        number_value := (p_value #>> '{}')::numeric;
        IF number_value <> trunc(number_value)
           OR abs(number_value) > 9007199254740991::numeric THEN
            RAISE EXCEPTION 'canonical JSON number is not a safe integer'
                USING ERRCODE = '22023';
        END IF;
        RETURN trunc(number_value)::text;
    ELSIF kind = 'boolean' THEN
        RETURN p_value #>> '{}';
    ELSIF kind = 'null' THEN
        RETURN 'null';
    END IF;
    RAISE EXCEPTION 'unsupported JSON value in canonical payload'
        USING ERRCODE = '22023';
END
$fn$;

REVOKE ALL ON FUNCTION task_execution.canonical_jsonb_text(jsonb) FROM PUBLIC;
-- V0002 grants EXECUTE on every function its owner creates in this schema to
-- the application role, so revoking PUBLIC is not enough: the canonicalizer is
-- a guard helper and no application session may call it.
REVOKE EXECUTE ON FUNCTION task_execution.canonical_jsonb_text(jsonb)
    FROM task_execution_app;

-- The promoted columns and the stored content address must agree with the
-- canonical payload: a snapshot cannot be published under a scope, DeliveryItem
-- mirror, schema version or hash that its own payload does not carry.
--
-- SECURITY DEFINER: the guard calls the owner-only canonicalizer, and a
-- permission check on that nested call is evaluated against the role that
-- performed the write. Running the guard as its owner keeps the canonicalizer
-- unreachable for the application role while every insert still re-derives the
-- content address in the database. The function only reads its own NEW row and
-- cannot be invoked directly (trigger functions are trigger-only).
CREATE FUNCTION task_execution.guard_task_definition_snapshot_mirror() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog
AS $guard$
BEGIN
    IF NEW.canonical_payload->'projectRef'->'scope'->>'enterpriseId'
          IS DISTINCT FROM NEW.enterprise_id::text
       OR NEW.canonical_payload->'projectRef'->'scope'->>'projectId'
          IS DISTINCT FROM NEW.project_id::text
       OR NEW.canonical_payload->'definition'->'deliveryItemRef'->>'objectId'
          IS DISTINCT FROM NEW.delivery_item_id::text
       OR NEW.canonical_payload->'definition'->'deliveryItemRef'->>'versionId'
          IS DISTINCT FROM NEW.delivery_item_version_id::text
       OR NEW.payload_hash
          IS DISTINCT FROM sha256(convert_to(
                 task_execution.canonical_jsonb_text(NEW.canonical_payload), 'UTF8')) THEN
        RAISE EXCEPTION 'task definition snapshot promoted mirror mismatch'
            USING ERRCODE = '22023';
    END IF;
    RETURN NEW;
END
$guard$;

REVOKE ALL ON FUNCTION task_execution.guard_task_definition_snapshot_mirror() FROM PUBLIC;

CREATE TRIGGER task_definition_snapshot_mirror_guard
    BEFORE INSERT OR UPDATE ON task_execution.task_definition_snapshot
    FOR EACH ROW EXECUTE FUNCTION task_execution.guard_task_definition_snapshot_mirror();

-- The promoted `schema_version` records the CREATE major that produced the
-- canonical payload (Spec 003 §16.4). Its truth is not derivable from the
-- payload alone: v1 `TaskDefinition` leaves `expectedOutputSpec` and
-- `completionCriteria` open, so a v1 payload may legally carry the closed v2
-- members, while a payload produced by `@2.0` must never be labelled `1.0`.
-- The producing command identity is what closes that direction: the Snapshot
-- must belong to the `command_receipt` of its own `source_command_id`, that
-- receipt must be the registered creation command, its version must equal the
-- promoted `schema_version`, and its target identity plus Scope must be this
-- Task. A relabelled or foreign-Snapshot insert therefore has no receipt to
-- agree with, while every row the owning runner writes has exactly one.
--
-- SECURITY INVOKER on purpose: the receipt is read under the same RLS policy
-- and trusted Scope the writer itself is subject to, so a hidden receipt is
-- indistinguishable from a missing one and fails closed.
CREATE FUNCTION task_execution.guard_task_definition_snapshot_creation_identity()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $guard$
DECLARE
    receipt_command_type text;
    receipt_command_version text;
    receipt_target_type text;
    receipt_target_id uuid;
    receipt_enterprise_id uuid;
    receipt_project_id uuid;
BEGIN
    SELECT r.command_type, r.command_version, r.target_type, r.target_id,
           r.enterprise_id, r.project_id
      INTO receipt_command_type, receipt_command_version, receipt_target_type,
           receipt_target_id, receipt_enterprise_id, receipt_project_id
      FROM task_execution.command_receipt r
     WHERE r.command_id = NEW.source_command_id
       AND r.command_type = 'execution.create_task';
    IF NOT FOUND
       OR receipt_command_version IS DISTINCT FROM NEW.schema_version
       OR receipt_target_type IS DISTINCT FROM (
              CASE NEW.schema_version
                  WHEN '2.0' THEN 'zhiju.execution.task'
                  ELSE 'execution.task'
              END)
       OR receipt_target_id IS DISTINCT FROM NEW.task_id
       OR receipt_enterprise_id IS DISTINCT FROM NEW.enterprise_id
       OR receipt_project_id IS DISTINCT FROM NEW.project_id THEN
        RAISE EXCEPTION 'task definition snapshot creation identity mismatch'
            USING ERRCODE = '22023';
    END IF;
    RETURN NEW;
END
$guard$;

REVOKE ALL ON FUNCTION task_execution.guard_task_definition_snapshot_creation_identity() FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION task_execution.guard_task_definition_snapshot_creation_identity()
    FROM task_execution_app;

CREATE TRIGGER task_definition_snapshot_creation_identity_guard
    BEFORE INSERT ON task_execution.task_definition_snapshot
    FOR EACH ROW EXECUTE FUNCTION task_execution.guard_task_definition_snapshot_creation_identity();

-- A committed Task definition is immutable history.
CREATE FUNCTION task_execution.guard_task_definition_snapshot_immutable() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $guard$
BEGIN
    RAISE EXCEPTION 'task_definition_snapshot history is immutable' USING ERRCODE = '23514';
END
$guard$;

REVOKE ALL ON FUNCTION task_execution.guard_task_definition_snapshot_immutable() FROM PUBLIC;

CREATE TRIGGER task_definition_snapshot_immutable_guard
    BEFORE UPDATE ON task_execution.task_definition_snapshot
    FOR EACH ROW EXECUTE FUNCTION task_execution.guard_task_definition_snapshot_immutable();

-- The Root keeps an update path for later lifecycle/CAS slices, but Task
-- identity, Project Scope, the DeliveryItem mirror and the creator attribution
-- are creation facts: a later command may move status/aggregate version and the
-- definition pointer, never the Scope.
CREATE FUNCTION task_execution.guard_task_scope_immutable() RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $guard$
BEGIN
    IF NEW.task_id IS DISTINCT FROM OLD.task_id
       OR NEW.enterprise_id IS DISTINCT FROM OLD.enterprise_id
       OR NEW.project_id IS DISTINCT FROM OLD.project_id
       OR NEW.delivery_item_id IS DISTINCT FROM OLD.delivery_item_id
       OR NEW.delivery_item_version_id IS DISTINCT FROM OLD.delivery_item_version_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR NEW.created_by_principal_id IS DISTINCT FROM OLD.created_by_principal_id THEN
        RAISE EXCEPTION 'task scope is immutable' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END
$guard$;

REVOKE ALL ON FUNCTION task_execution.guard_task_scope_immutable() FROM PUBLIC;

CREATE TRIGGER task_scope_immutable_guard
    BEFORE UPDATE ON task_execution.task
    FOR EACH ROW EXECUTE FUNCTION task_execution.guard_task_scope_immutable();

-- Immutable definition facts and roots: no UPDATE/DELETE path for the app role.
REVOKE UPDATE, DELETE ON task_execution.task_definition_snapshot FROM task_execution_app;
REVOKE DELETE ON task_execution.task FROM task_execution_app;

