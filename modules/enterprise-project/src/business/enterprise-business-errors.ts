/**
 * Stable, safe business failure code. Never carries the offending payload.
 * Implements the same shape as `CommandExecutionError` so callers can
 * distinguish business-domain rejection (REJECTED result) from transaction
 * infrastructure failures.
 */
export class EnterpriseBusinessError extends Error {
  constructor(
    readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'EnterpriseBusinessError';
  }
}

/** Stable code surface returned by business handlers. */
export type EnterpriseBusinessErrorCode =
  | typeof PROJECT_ENTERPRISE_NOT_ACTIVE
  | typeof PROJECT_FACT_SOURCE_REQUIRED
  | typeof PROJECT_FACT_CONFIRMATION_FORBIDDEN
  | typeof PROJECT_FACT_CONFLICT_UNRESOLVED
